describe('AcDbAcadRustNativeConverter NOD dictionary wiring (M4.9b)', () => {
  let nodDb: AcDbDatabase
  let nodBaselineDb: AcDbDatabase

  beforeAll(async () => {
    nodDb = (await readNative()).db
    nodBaselineDb = await readBaseline()
  })

  /** objectId/ownerId getters throw when the attrs slot was never assigned. */
  function safeId(obj: any, key: 'objectId' | 'ownerId'): string | undefined {
    try {
      return obj[key]
    } catch {
      return undefined
    }
  }

  /** Root dictionary of the committed fixture (the owner-0 DICTIONARY). */
  function fixtureRoot(): any {
    const table = loadJson('objects.json')
    return Object.values(table)
      .map((v: any) => v.Dictionary)
      .find((d: any) => d && d.owner === 0)
  }

  /** Same key whitelist the Architecture-A DXF reader binds typed slots to. */
  const WHITELIST: Record<string, string> = {
    ACAD_LAYOUT: 'layout',
    ACAD_GROUP: 'group',
    ACAD_SORTENTS: 'sortentsTable',
    ACAD_MLEADERSTYLE: 'mleaderStyle',
    ACAD_MLINESTYLE: 'mlineStyle',
    ISM_RASTER_IMAGE_DICT: 'imageDefinition',
    MLIGHT_XRECORD: 'xrecord'
  }

  it('wires the NOD root like the baseline: hex id, owner 0, whitelist-only keys', () => {
    const root = fixtureRoot()
    expect(root).toBeDefined()
    const expectedKeys = root.entries
      .filter(([k]: [string, number]) => WHITELIST[k.toUpperCase()])
      .map(([k]: [string, number]) => k)
      .sort()
    expect(expectedKeys.length).toBeGreaterThan(0)
    const nativeKeys = [...nodDb.objects.dictionary.entries()].map(([k]) => k).sort()
    expect(nativeKeys).toEqual(expectedKeys)
    const baselineKeys = [...nodBaselineDb.objects.dictionary.entries()].map(([k]) => k).sort()
    expect(nativeKeys).toEqual(baselineKeys)
    expect(safeId(nodDb.objects.dictionary, 'objectId')).toBe('C')
    expect(safeId(nodDb.objects.dictionary, 'objectId')).toBe(
      safeId(nodBaselineDb.objects.dictionary, 'objectId')
    )
    expect(safeId(nodDb.objects.dictionary, 'ownerId')).toBe('0')
  })

  it('binds each typed child dictionary to the DWG child handle, matching the baseline ids', () => {
    const root = fixtureRoot()
    let wired = 0
    for (const [key, childHandle] of root.entries) {
      const slot = WHITELIST[key.toUpperCase()]
      if (!slot) {
        continue
      }
      wired++
      const native = (nodDb.objects as any)[slot]
      const baseline = (nodBaselineDb.objects as any)[slot]
      const expectedId = (childHandle as number).toString(16).toUpperCase()
      expect(String(safeId(native, 'objectId'))).toBe(expectedId)
      expect(safeId(native, 'objectId')).toBe(safeId(baseline, 'objectId'))
      expect(safeId(native, 'ownerId')).toBe(safeId(baseline, 'ownerId'))
    }
    expect(wired).toBeGreaterThan(0)
  })

  it('leaves non-whitelist root keys unwired, exactly as the baseline does', () => {
    // ACAD_SCALELIST / ACAD_VISUALSTYLE / ACAD_PLOTSTYLENAME live in the DWG
    // root but the reader semantics (and hence the baseline) never hang them;
    // their payload types have no data-model class yet.
    for (const key of ['ACAD_SCALELIST', 'ACAD_VISUALSTYLE', 'ACAD_PLOTSTYLENAME']) {
      expect(fixtureRoot().entries.some(([k]: [string, number]) => k === key)).toBe(true)
      expect(nodDb.objects.dictionary.has(key)).toBe(false)
      expect(nodBaselineDb.objects.dictionary.has(key)).toBe(false)
    }
  })

  it('resolves dictionary entries through the two-pass handle graph (synthetic MLIGHT_XRECORD)', async () => {
    // Real objects.json keeps all 27 xrecords; the root + one child dictionary
    // are overridden so a whitelist key targets a dictionary whose entries
    // reference a resident xrecord by handle - the fill path the real corpus
    // cannot exercise (its payload types are not mapped yet).
    const real = loadJson('objects.json')
    const synthetic = {
      ...real,
      '12': {
        Dictionary: {
          handle: 12,
          owner: 0,
          entries: [['MLIGHT_XRECORD', 200]],
          duplicate_cloning: 1,
          hard_owner: false
        }
      },
      '200': {
        Dictionary: {
          handle: 200,
          owner: 12,
          entries: [['FOO', 4806], ['MISSING', 999999]],
          duplicate_cloning: 1,
          hard_owner: false
        }
      }
    }
    const db = (await readNative({ objects: synthetic })).db
    expect([...db.objects.dictionary.entries()].map(([k]) => k)).toEqual(['MLIGHT_XRECORD'])
    expect(String(db.objects.xrecord.objectId)).toBe('C8')
    expect(safeId(db.objects.xrecord, 'ownerId')).toBe('C')
    // 'FOO' resolves to the same resident xrecord instance as its handle key;
    // 'MISSING' (unreferenced handle) is skipped without throwing.
    expect(db.objects.xrecord.getAt('FOO')).toBe(db.objects.xrecord.getAt('12C6'))
    expect(db.objects.xrecord.has('MISSING')).toBe(false)
    expect(db.objects.xrecord.numEntries).toBe(28) // 27 handle-keyed + FOO alias
  })
})

