describe('AcDbAcadRustNativeConverter complex-linetype mapping', () => {
  const shapeStyle = {
    handle: 41493,
    name: 'LT-SHAPE-FONT',
    flags: { backward: false, upside_down: false },
    height: 0,
    width_factor: 1,
    oblique_angle: 0,
    last_height: 0.2,
    font_file: 'ltypeshp.shx',
    big_font_file: '',
    true_type_font: '',
    true_type_font_flags: 0,
    xref_dependent: false,
    xref_block_record_handle: 0,
    is_shape_file: true,
    is_vertical: false,
    annotative: false
  }

  /**
   * A probe linetype mirroring the real `jtbj-1` (井田边界) embedded-SHAPE
   * segment, plus a plain dash, a LibreDWG pseudo-complex (shape_number 0) dash
   * and an absolute-rotation embedded-TEXT segment. Committed on top of the real
   * LTYPE / STYLE fixtures so the standard entries stay present.
   */
  async function convertComplexProbe(): Promise<{
    db: AcDbDatabase
    pattern: any[]
  }> {
    const baseLtype = loadJson('tables-ltype.json')
    const baseStyle = loadJson('tables-style.json')
    const probe = {
      handle: 3688244,
      name: 'TEST-CX',
      description: 'complex probe',
      elements: [
        { length: 20, complex: null },
        {
          length: 5,
          complex: {
            content: { Shape: { shape_number: 130 } },
            style_handle: 41493,
            scale: 2.5,
            rotation: 0,
            absolute_rotation: false,
            offset: [-2.5, 0]
          }
        },
        {
          length: 0,
          complex: {
            content: { Shape: { shape_number: 0 } },
            style_handle: 0,
            scale: 0,
            rotation: 0,
            absolute_rotation: false,
            offset: [0, 0]
          }
        },
        {
          length: 4,
          complex: {
            content: { Text: { text: 'AB' } },
            style_handle: 41493,
            scale: 1,
            rotation: 0.5,
            absolute_rotation: true,
            offset: [0, -0.86]
          }
        }
      ],
      pattern_length: 29,
      alignment: 'A',
      xref_dependent: false,
      xref_block_record_handle: 0
    }
    const lineTypes = {
      ...baseLtype,
      entries: { ...baseLtype.entries, 'TEST-CX': probe }
    }
    const textStyles = {
      ...baseStyle,
      entries: { ...baseStyle.entries, 'LT-SHAPE-FONT': shapeStyle }
    }
    const { db } = await readNative({ lineTypes, textStyles })
    const record = db.tables.linetypeTable.getAt('TEST-CX') as any
    return { db, pattern: record.linetype.pattern as any[] }
  }

  it('maps an embedded SHAPE segment with flag / shape-number / style name', async () => {
    const { db, pattern } = await convertComplexProbe()
    const shape = pattern[1]
    expect(shape.elementTypeFlag).toBe(4)
    expect(shape.shapeNumber).toBe(130)
    expect(shape.scale).toBe(2.5)
    expect(shape.offsetX).toBe(-2.5)
    expect(shape.offsetY).toBe(0)
    // `styleObjectId` is rewritten from the dangling DWG hex (0x2B1-style) to the
    // native objectId of the shape-file STYLE record, so the renderer's
    // `openObjectForRead` resolves the embedded font (the only path for empty-name
    // shape fonts). The name is still carried as a secondary fallback.
    expect(shape.styleObjectId).not.toBe('A215')
    expect(shape.style).toBe('LT-SHAPE-FONT')
    const resolved = db.openObjectForRead(shape.styleObjectId) as any
    expect(resolved).toBeTruthy()
    expect(resolved.name).toBe('LT-SHAPE-FONT')
    expect(resolved.isShapeFile).toBe(true)
  })

  it('keeps plain and pseudo-complex (shape_number 0) dashes simple', async () => {
    const { pattern } = await convertComplexProbe()
    expect(pattern[0]).toEqual({ elementLength: 20, elementTypeFlag: 0 })
    expect(pattern[2].elementTypeFlag).toBe(0)
    expect(pattern[2].shapeNumber).toBeUndefined()
    expect(pattern[2].style).toBeUndefined()
  })

  it('maps an embedded TEXT segment with the absolute-rotation bit and text', async () => {
    const { pattern } = await convertComplexProbe()
    const text = pattern[3]
    // 1 (absolute rotation) | 2 (embedded text).
    expect(text.elementTypeFlag).toBe(3)
    expect(text.text).toBe('AB')
    expect(text.shapeNumber).toBeUndefined()
    expect(text.rotation).toBe(0.5)
    expect(text.style).toBe('LT-SHAPE-FONT')
  })
})
