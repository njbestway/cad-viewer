/**
 * Phase 4 §7 parity harness (hermetic, no worker / no wasm).
 *
 * Node cannot load the `--target web` wasm glue, so the real
 * {@link AcadRustWorkerDocumentClient} is untestable here. Instead we inject a
 * fake {@link AcadRustDocumentClient} that replays the committed
 * `fixtures/sample-drawing/*.json` (regenerated by the offline native dumper),
 * driving the *pure TS* section -> database mapping inside
 * {@link AcDbAcadRustNativeConverter}.
 *
 * The result is then compared structurally against the Architecture-A baseline:
 * the same drawing transcoded to `baseline.dxf` and read by the MIT
 * {@link AcDbNativeDxfConverter}. Header scalars and the LAYER / LTYPE / STYLE
 * record sets must agree — that agreement is exactly what makes the native path
 * a drop-in for A (Gate 2 for Slice 0).
 */
const FIXTURE_DIR = join(__dirname, 'fixtures', 'sample-drawing')

function loadJson(name: string): any {
  return JSON.parse(readFileSync(join(FIXTURE_DIR, name), 'utf8'))
}

/**
 * Replays the committed fixtures through the sectioned protocol. `open` hands
 * back a fixed handle; `section` maps each kind to its `<kind>.json` (a
 * `blockRecords` override swaps in a synthetic BLOCK-RECORD table). Model-space
 * entities come from `page`; block-definition entities from `blockPages` (keyed
 * by block name). Defaults reproduce the committed sample-drawing replay.
 */
interface FixtureOptions {
  /** Served model-space page. */
  page?: any[]
  /** Block-definition pages keyed by block name. */
  blockPages?: Record<string, any[]>
  /** Synthetic BLOCK-RECORD section (overrides the committed one). */
  blockRecords?: any
  /** Synthetic OBJECTS section (overrides the committed objects.json). */
  objects?: any
  /** Synthetic LTYPE section (overrides the committed tables-ltype.json). */
  lineTypes?: any
  /** Synthetic STYLE section (overrides the committed tables-style.json). */
  textStyles?: any
}

class FixtureClient implements AcadRustDocumentClient {
  closed = 0
  readonly opened: number[] = []

  private readonly page: any[]
  private readonly blockPages: Record<string, any[]>
  private readonly blockRecords: any
  private readonly objects: any
  private readonly lineTypes: any
  private readonly textStyles: any

  constructor(opts: FixtureOptions = {}) {
    this.page = opts.page ?? loadJson('entity-page-0.json')
    this.blockPages = opts.blockPages ?? {}
    this.blockRecords = opts.blockRecords
    this.objects = opts.objects
    this.lineTypes = opts.lineTypes
    this.textStyles = opts.textStyles
  }

   async open(_data: ArrayBuffer): Promise<number> {
    this.opened.push(1)
    return 1
  }

   async meta(_handle: number): Promise<any> {
    return loadJson('meta.json')
  }

   async section<T>(_handle: number, kind: AcadRustSectionKind): Promise<T> {
    if (kind === 'tables-blockrecord' && this.blockRecords !== undefined) {
      return this.blockRecords as T
    }
    if (kind === 'objects' && this.objects !== undefined) {
      return this.objects as T
    }
    if (kind === 'tables-ltype' && this.lineTypes !== undefined) {
      return this.lineTypes as T
    }
    if (kind === 'tables-style' && this.textStyles !== undefined) {
      return this.textStyles as T
    }
    return loadJson(`${kind}.json`) as T
  }

   async entityPage(_handle: number, offset: number): Promise<any[]> {
    // The offline dumper committed only the first model-space page; serving it
    // at offset 0 (and an empty page beyond) exercises the paging loop's
    // short-page termination exactly as a single-page draw would. Synthetic
    // geometry tests inject a single-page array instead.
    return offset === 0 ? this.page : []
  }

   async blockEntityPage(
    _handle: number,
    blockName: string,
    offset: number
  ): Promise<any[]> {
    // Real fixture carries no committed block bodies; synthetic block tests
    // inject pages per block name. Empty first page terminates the block loop.
    return offset === 0 ? this.blockPages[blockName] ?? [] : []
  }

  async blockEntitiesBatch(
    _handle: number,
    blockNames: string[]
  ): Promise<{ name: string; entities: any[] }[]> {
    // The batched path returns each definition's complete list; synthetic tests
    // inject those lists through the same `blockPages` map.
    return blockNames.map(name => ({
      name,
      entities: this.blockPages[name] ?? []
    }))
  }

   async close(_handle: number): Promise<void> {
    this.closed++
  }

  dispose(): void {
    // no transport to tear down
  }
}

/** Collect a symbol table's record names, normalized for set comparison. */
function tableNames(
  db: AcDbDatabase,
  which: 'layer' | 'linetype' | 'textstyle' | 'dimstyle' | 'vport'
): string[] {
  const table =
    which === 'layer'
      ? db.tables.layerTable
      : which === 'linetype'
        ? db.tables.linetypeTable
        : which === 'dimstyle'
          ? db.tables.dimStyleTable
          : which === 'vport'
            ? db.tables.viewportTable
            : db.tables.textStyleTable
  const names: string[] = []
  for (const record of table.newIterator()) {
    names.push(String((record as any).name).trim().toUpperCase())
  }
  return names.sort()
}

/** Read a fixture-driven native database. */
async function readNative(arg?: any[] | FixtureOptions): Promise<{
  db: AcDbDatabase
  client: FixtureClient
  unknownEntityCount: number
}> {
  const opts: FixtureOptions = Array.isArray(arg) ? { page: arg } : arg ?? {}
  const client = new FixtureClient(opts)
  const db = new AcDbDatabase()
  // The sectioned mapper bypasses the open-for-write guard by building records
  // through their attribute constructors, but keep the working database bound so
  // any event side-effects resolve against it (matches how a host drives read()).
  acdbAssignWorkingDatabase(db)
  const converter = new AcDbAcadRustNativeConverter({ client })
  // Capture the ENTITY-END stats (unknown count) via the progress callback.
  let unknownEntityCount = -1
  // Slice 0 never touches the bytes (the client replays fixtures), so an empty
  // buffer is fine; the header/tables come purely from the injected sections.
  await converter.read(new ArrayBuffer(0), db, {
    progress: async (_pct, _stage, _status, data) => {
      if (data && typeof data === 'object' && 'unknownEntityCount' in (data as any)) {
        unknownEntityCount = (data as any).unknownEntityCount
      }
    }
  })
  return { db, client, unknownEntityCount }
}

/** Read the Architecture-A baseline database from the transcoded DXF. */
async function readBaseline(): Promise<AcDbDatabase> {
  const text = readFileSync(join(FIXTURE_DIR, 'baseline.dxf'))
  // Copy into a standalone, zero-offset ArrayBuffer (the DXF decoder requires an
  // exact-length buffer, matching what the worker hands the A converter).
  const buf = new ArrayBuffer(text.byteLength)
  new Uint8Array(buf).set(new Uint8Array(text.buffer, text.byteOffset, text.byteLength))
  const db = new AcDbDatabase()
  // The built-in DXF reader opens records for write, which resolves the current
  // working database through the host application services — bind `db` first.
  acdbAssignWorkingDatabase(db)
  const converter = new AcDbNativeDxfConverter({ useWorker: false })
  await converter.read(buf, db)
  return db
}

/**
 * Read a native database whose model space is fed a caller-supplied page, while
 * header/tables still replay the committed fixtures. Used to exercise geometry
 * classes (CIRCLE/ARC/ELLIPSE/POLYLINE/SPLINE) that the sample drawing's first
 * page does not happen to contain, without depending on a specific corpus file.
 */
async function readEntities(entities: any[]): Promise<AcDbDatabase> {
  const { db } = await readNative(entities)
  return db
}

/** Collect model-space entities that are instances of `Ctor`. */
function collect<T>(db: AcDbDatabase, Ctor: new (...args: any[]) => T): T[] {
  return collectFrom(db.tables.blockTable.modelSpace, Ctor)
}

/** Collect entities of `Ctor` held in a named block definition. */
function collectInBlock<T>(
  db: AcDbDatabase,
  blockName: string,
  Ctor: new (...args: any[]) => T
): T[] {
  const record = db.tables.blockTable.getAt(blockName)
  return record ? collectFrom(record, Ctor) : []
}

function collectFrom<T>(
  record: AcDbBlockTableRecord,
  Ctor: new (...args: any[]) => T
): T[] {
  const out: T[] = []
  for (const entity of record.newIterator()) {
    if (entity instanceof Ctor) {
      out.push(entity as T)
    }
  }
  return out
}

/** All non-space block-definition names in a database, normalized + sorted. */
function blockNames(db: AcDbDatabase): string[] {
  const out: string[] = []
  for (const record of db.tables.blockTable.newIterator()) {
    const name = String((record as any).name ?? '')
    if (!name) {
      continue
    }
    if (
      AcDbBlockTableRecord.isModelSapceName(name) ||
      AcDbBlockTableRecord.isPaperSapceName(name)
    ) {
      continue
    }
    out.push(name.trim().toUpperCase())
  }
  return out.sort()
}

